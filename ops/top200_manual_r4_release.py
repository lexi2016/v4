def isolated_smoke(payload, manifest_sha):
    env = {**os.environ, **payload['EnvironmentVariables']}
    args = payload['ProgramArguments']
    if args[1:5] != ['-B', '-m', 'apps.api.v4_api.run', '--host'] or args[5:8] != ['127.0.0.1', '--port', '8873']:
        raise ValueError('LIVE_PROGRAM_ARGUMENTS_UNEXPECTED')
    with socket.socket() as s:
        s.bind(('127.0.0.1', 0))
        port = s.getsockname()[1]
    env['V4_API_PORT'] = str(port)
    log = TARGET / 'isolated-smoke.log'
    with log.open('x') as output:
        process = subprocess.Popen([sys.executable, *args[1:7], str(port), *args[8:]], cwd=payload['WorkingDirectory'],
                                   env=env, stdout=output, stderr=subprocess.STDOUT)
        try:
            deadline = time.monotonic() + 45
            error = None
            while time.monotonic() < deadline:
                if process.poll() is not None:
                    raise RuntimeError('SMOKE_PROCESS_EXITED:' + str(process.returncode))
                try:
                    result = verify_http(port, release_id=TARGET.name, manifest_sha=manifest_sha, single=True)
                    return {'status': 'PASS', 'port': port, 'python': sys.executable, **result}
                except (OSError, ValueError, KeyError, json.JSONDecodeError) as exc:
                    error = repr(exc)
                    time.sleep(0.25)
            raise RuntimeError('SMOKE_TIMEOUT:' + str(error))
        finally:
            process.terminate()
            try:
                process.wait(timeout=10)
            except subprocess.TimeoutExpired:
                process.kill()
                process.wait(timeout=5)


