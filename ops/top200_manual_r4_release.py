def bootstrap_validate(raw, *, single, tracking=None, capture=None):
    result = launchctl('bootstrap', DOMAIN, str(PLIST))
    if result.returncode:
        raise RuntimeError('BOOTSTRAP_FAILED:' + result.stderr)
    env = plistlib.loads(raw)['EnvironmentVariables']
    deadline = time.monotonic() + 45
    error = None
    while time.monotonic() < deadline:
        try:
            process = live_process()
        except (OSError, ValueError, subprocess.SubprocessError) as exc:
            error = repr(exc)
            time.sleep(0.3)
            continue
        if tracking is not None:
            if tracking.get('process') is None:
                if capture is not None:
                    capture(process)
                tracking['process'] = process
            elif tracking['process'] != process:
                raise ValueError('BOOTSTRAPPED_PROCESS_CHANGED')
        try:
            http = verify_http(8873, release_id=env['V4_RELEASE_ID'],
                               manifest_sha=env['V4_RELEASE_MANIFEST_SHA256'], single=single)
            return process, http
        except (OSError, ValueError, KeyError, subprocess.SubprocessError) as exc:
            error = repr(exc)
            time.sleep(0.3)
    raise RuntimeError('READINESS_TIMEOUT:' + str(error))


