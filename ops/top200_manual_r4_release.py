def base_inventory(tools, stage):
    raw = checked(BASE / 'release-manifest.json', BASE_MANIFEST_SHA).read_bytes()
    manifest = json.loads(raw)
    expected = {'root': str(BASE), 'app_root': str(BASE / 'app'),
                'release_id': BASE.name, 'module_role': 'api'}
    if manifest.get('schema_version') != 'v4.release_candidate.v1' or manifest.get('candidate') != expected:
        raise ValueError('BASE_MANIFEST_IDENTITY_CHANGED')
    inventory = tools.inventory_tree(BASE / 'app')
    record = manifest['application_inventory']
    original = record['entries']
    if (record['entry_count'] != len(original)
            or record['aggregate_sha256'] != tools.inventory_digest(original)
            or manifest['app_files'] != original):
        raise ValueError('BASE_APPLICATION_INVENTORY_CHANGED')
    drift_ref = stage.get('base_inventory_drift')
    if drift_ref:
        drift = json.loads(ref_checked(drift_ref).read_text())
        addition = BASE_CACHE_ADDITION
        change = {'path': addition['path'], 'before': None, 'after': addition}
        if (drift.get('schema') != 'v4.api_base_inventory_drift.v1'
                or drift.get('base_root') != str(BASE)
                or drift.get('base_manifest_sha256') != BASE_MANIFEST_SHA
                or drift.get('manifest_pinned_sha256') != BASE_MANIFEST_SHA
                or drift.get('manifest_inventory_count') != len(original)
                or drift.get('manifest_inventory_digest') != record['aggregate_sha256']
                or drift.get('changes') != [change]
                or drift.get('delta_overlap') != []
                or any(item['path'] == addition['path'] for item in original)
                or inventory != sorted(original + [addition], key=lambda item: item['path'])
                or drift.get('actual_inventory_count') != len(inventory)
                or drift.get('actual_inventory_digest') != tools.inventory_digest(inventory)):
            raise ValueError('BASE_APPLICATION_INVENTORY_CHANGED')
    elif original != inventory:
        raise ValueError('BASE_APPLICATION_INVENTORY_CHANGED')
    return manifest, inventory


