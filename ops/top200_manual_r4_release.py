def launchctl(*args):
    return subprocess.run(['/bin/launchctl', *args], text=True, capture_output=True, timeout=10)


def live_process():
    printed = launchctl('print', JOB)
    match = re.search(r'\bpid = (\d+)', printed.stdout)
    if printed.returncode or not match:
        raise ValueError('LIVE_JOB_PID_MISSING')
    pid = int(match.group(1))
    output = subprocess.check_output(['/usr/sbin/lsof', '-nP', '-iTCP:8873', '-sTCP:LISTEN', '-t'], text=True, timeout=5)
    if set(output.split()) != {str(pid)}:
        raise ValueError('LIVE_LISTENER_PID_MISMATCH')
    started = subprocess.check_output(['/bin/ps', '-p', str(pid), '-o', 'lstart=', '-o', 'command='], text=True, timeout=5).strip()
    if not started:
        raise ValueError('LIVE_PROCESS_IDENTITY_MISSING')
    return {'pid': pid, 'start_and_command': started}


def assert_live_root(pid, expected_root):
    environment = subprocess.check_output(['/bin/ps', 'eww', '-p', str(pid), '-o', 'command='], text=True, timeout=5)
    match = re.search(r'(?:^|\s)V4_APP_ROOT=(.*?)(?=\s+[A-Za-z_][A-Za-z_0-9]*=|$)', environment)
    if not match or match.group(1) != expected_root:
        raise ValueError('ACTIVE_PROCESS_ROOT_CAS_CHANGED')


def fetch(port, route):
    opener = urllib.request.build_opener(urllib.request.ProxyHandler({}))
    with opener.open(f'http://127.0.0.1:{port}' + route, timeout=20) as response:
        return response.read()


