def service_state():
    result = launchctl('print', JOB)
    if result.returncode == 0:
        return 'running', live_process()
    if 'Could not find service' not in result.stderr:
        raise ValueError('RECOVERY_JOB_STATE_UNKNOWN')
    listeners = subprocess.run(['/usr/sbin/lsof', '-nP', '-iTCP:8873', '-sTCP:LISTEN', '-t'],
                               text=True, capture_output=True, timeout=5)
    if listeners.returncode not in (0, 1) or listeners.stdout.strip():
        raise ValueError('RECOVERY_UNOWNED_LISTENER')
    return 'stopped', None


def recover_previous(*, previous, desired, expected_process, tracking, previous_single, expected_pool):
    current = PLIST.read_bytes()
    if current not in (previous, desired):
        raise ValueError('RECOVERY_PLIST_CAS_CONFLICT')
    state, process = service_state()
    if state == 'running' and current == previous:
        if process != expected_process:
            raise ValueError('RECOVERY_PREVIOUS_PROCESS_CHANGED')
        env = plistlib.loads(previous)['EnvironmentVariables']
        result = verify_http(8873, release_id=env['V4_RELEASE_ID'],
                             manifest_sha=env['V4_RELEASE_MANIFEST_SHA256'], single=previous_single)
        if result['pool_rows_sha256'] != expected_pool:
            raise ValueError('RECOVERY_PREVIOUS_POOL_CHANGED')
        return process, result
    if state == 'running':
        if not tracking.get('process') or process != tracking['process'] or PLIST.read_bytes() != desired:
            raise ValueError('RECOVERY_DESIRED_PROCESS_UNCONFIRMED')
        unload()
        state, _ = service_state()
        if state != 'stopped':
            raise ValueError('RECOVERY_UNLOAD_NOT_CONFIRMED')
    if PLIST.read_bytes() != current:
        raise ValueError('RECOVERY_PLIST_CHANGED_AFTER_UNLOAD')
    if current != previous:
        atomic_plist(previous)
    process, result = bootstrap_validate(previous, single=previous_single)
    if result['pool_rows_sha256'] != expected_pool:
        raise ValueError('RECOVERY_RESTORED_POOL_CHANGED')
    return process, result


def switch(*, receipt_sha, rollback=False, activation_sha=None):
    with release_lock():
        stage, _, _ = load_stage()
        receipt = json.loads(checked(RECEIPT, receipt_sha).read_text())
        old, new = BACKUP.read_bytes(), STAGED_PLIST.read_bytes()
        if receipt.get('status') != 'PREPARED_NOT_ACTIVATED' or receipt.get('smoke', {}).get('status') != 'PASS':
            raise ValueError('PREPARATION_NOT_VERIFIED')
        if rollback:
            active = json.loads(checked(ACTIVE_RECEIPT, activation_sha).read_text())
            if active['candidate_plist_sha256'] != receipt['candidate_plist_sha256']:
                raise ValueError('ROLLBACK_RECEIPT_CHANGED')
            expected_sha, expected_process = receipt['candidate_plist_sha256'], active['process']
        else:
            if ACTIVE_RECEIPT.exists() or ATTEMPT.exists():
                raise ValueError('ACTIVATION_RECEIPT_OR_ATTEMPT_EXISTS_USE_RECOVERY')
            expected_sha, expected_process = PLIST_SHA, receipt['base_process']
        assert_switch_identity(current_plist_sha=file_sha(PLIST), expected_plist_sha=expected_sha,
                               current_process=live_process(), expected_process=expected_process)
        verify_candidate(receipt, stage, require_base_plist=not rollback)
        old_env, new_env = plistlib.loads(old)['EnvironmentVariables'], plistlib.loads(new)['EnvironmentVariables']
        env = new_env if rollback else old_env
        before = verify_http(8873, release_id=env['V4_RELEASE_ID'], manifest_sha=env['V4_RELEASE_MANIFEST_SHA256'], single=rollback)
        if before['pool_rows_sha256'] != receipt['base_live']['pool_rows_sha256']:
            raise ValueError('LIVE_POOL_CHANGED_BEFORE_SWITCH')
        desired, previous = (old, new) if rollback else (new, old)
        tracking = {}
        capture = None
        if not rollback:
            attempt = {'schema': 'junda_single_activation_attempt.v1', 'status': 'BEFORE_UNLOAD',
                       'preparation_sha256': receipt_sha, 'stage_sha256': STAGE_SHA,
                       'before_plist_sha256': PLIST_SHA, 'candidate_plist_sha256': receipt['candidate_plist_sha256'],
                       'before_plist_path': str(BACKUP), 'candidate_plist_path': str(STAGED_PLIST),
                       'before_manifest_sha256': BASE_MANIFEST_SHA, 'candidate_manifest_sha256': receipt['manifest_sha256'],
                       'before_process': expected_process, 'candidate_process': None}
            attempt_sha = persist_attempt(attempt)
            def capture(process):
                nonlocal attempt_sha
                attempt['candidate_process'] = process
                attempt['status'] = 'CANDIDATE_PROCESS_CAPTURED'
                attempt_sha = persist_attempt(attempt, expected_sha=attempt_sha)
        # Expensive inventory/HTTP checks ran after the first CAS. Recheck the
        # actual process and root immediately before bootout while holding the
        # shared lock; a concurrent owner's drift must never reach unload().
        assert_switch_identity(current_plist_sha=file_sha(PLIST), expected_plist_sha=expected_sha,
                               current_process=live_process(), expected_process=expected_process)
        assert_live_root(expected_process['pid'], env['V4_APP_ROOT'])
        assert_switch_identity(current_plist_sha=file_sha(PLIST), expected_plist_sha=expected_sha,
                               current_process=live_process(), expected_process=expected_process)
        try:
            unload()
            if file_sha(PLIST) != expected_sha:
                raise ValueError('ACTIVE_PLIST_CAS_CHANGED_AFTER_UNLOAD')
            atomic_plist(desired)
            process, result = bootstrap_validate(desired, single=not rollback, tracking=tracking, capture=capture)
            if result['pool_rows_sha256'] != receipt['base_live']['pool_rows_sha256']:
                raise ValueError('LIVE_POOL_CHANGED_AFTER_SWITCH')
            for path, digest in POINTERS.items():
                checked(path, digest)
            if not rollback:
                json_write(ACTIVE_RECEIPT, {'status': 'ACTIVATED_VERIFIED', 'candidate_plist_sha256': receipt['candidate_plist_sha256'],
                                           'process': process, 'http': result, 'inverse_plist_sha256': PLIST_SHA,
                                           'attempt_sha256': attempt_sha})
            else:
                json_write(TARGET / 'rollback.json', {'status': 'ROLLBACK_VERIFIED', 'process': process, 'http': result})
        except BaseException as primary:
            try:
                recover_previous(previous=previous, desired=desired, expected_process=expected_process,
                                 tracking=tracking, previous_single=rollback,
                                 expected_pool=receipt['base_live']['pool_rows_sha256'])
            except BaseException as recovery:
                raise RuntimeError(f'CUTOVER_FAILED:{primary!r}; AUTOMATIC_ROLLBACK_FAILED:{recovery!r}') from primary
            raise RuntimeError(f'CUTOVER_FAILED:{primary!r}; AUTOMATIC_ROLLBACK_VERIFIED') from primary
        print(json.dumps({'status': 'ROLLBACK_VERIFIED' if rollback else 'ACTIVATED_VERIFIED', 'process': process,
                          'activation_receipt_sha256': file_sha(ACTIVE_RECEIPT)}))


def recover_interrupted(*, receipt_sha, attempt_sha):
    with release_lock():
        stage, _, _ = load_stage()
        receipt = json.loads(checked(RECEIPT, receipt_sha).read_text())
        attempt = json.loads(checked(ATTEMPT, attempt_sha).read_text())
        if ACTIVE_RECEIPT.exists():
            raise ValueError('ACTIVATION_RECEIPT_EXISTS_USE_ROLLBACK')
        if (attempt.get('schema') != 'junda_single_activation_attempt.v1'
                or attempt.get('preparation_sha256') != receipt_sha or attempt.get('stage_sha256') != STAGE_SHA
                or attempt.get('before_plist_sha256') != PLIST_SHA
                or attempt.get('candidate_plist_sha256') != receipt['candidate_plist_sha256']
                or attempt.get('before_manifest_sha256') != BASE_MANIFEST_SHA
                or attempt.get('candidate_manifest_sha256') != receipt['manifest_sha256']
                or attempt.get('before_plist_path') != str(BACKUP)
                or attempt.get('candidate_plist_path') != str(STAGED_PLIST)
                or attempt.get('before_process') != receipt['base_process']):
            raise ValueError('RECOVERY_ATTEMPT_IDENTITY_CHANGED')
        verify_candidate(receipt, stage, require_base_plist=False)
        old, new = BACKUP.read_bytes(), STAGED_PLIST.read_bytes()
        state, process = service_state()
        if state == 'running' and PLIST.read_bytes() == new:
            if process != attempt.get('candidate_process'):
                raise ValueError('RECOVERY_CANDIDATE_PROCESS_CHANGED')
            env = plistlib.loads(new)['EnvironmentVariables']
            observed = verify_http(8873, release_id=env['V4_RELEASE_ID'],
                                   manifest_sha=env['V4_RELEASE_MANIFEST_SHA256'], single=True)
            if observed['pool_rows_sha256'] != receipt['base_live']['pool_rows_sha256']:
                raise ValueError('RECOVERY_CANDIDATE_POOL_CHANGED')
        process, result = recover_previous(previous=old, desired=new, expected_process=attempt['before_process'],
                                           tracking={'process': attempt.get('candidate_process')}, previous_single=False,
                                           expected_pool=receipt['base_live']['pool_rows_sha256'])
        json_write(TARGET / 'interrupted-recovery.json', {'status': 'INTERRUPTED_ACTIVATION_ROLLED_BACK',
                   'attempt_sha256': attempt_sha, 'preparation_sha256': receipt_sha, 'process': process, 'http': result})
        print(json.dumps({'status': 'INTERRUPTED_ACTIVATION_ROLLED_BACK', 'process': process}))


def check(receipt_sha):
    with release_lock():
        stage, _, _ = load_stage()
        receipt = json.loads(checked(RECEIPT, receipt_sha).read_text())
        verify_candidate(receipt, stage, require_base_plist=True)
        assert_switch_identity(current_plist_sha=file_sha(PLIST), expected_plist_sha=PLIST_SHA,
                               current_process=live_process(), expected_process=receipt['base_process'])
        print(json.dumps({'status': 'PREPARED_PREFLIGHT_PASS', 'receipt': str(RECEIPT),
                          'manifest_sha256': receipt['manifest_sha256']}))


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('action', choices=('prepare', 'check', 'activate', 'rollback', 'recover'))
    parser.add_argument('--stage', required=True)
    parser.add_argument('--stage-sha256', required=True)
    parser.add_argument('--receipt-sha256')
    parser.add_argument('--activation-sha256')
    parser.add_argument('--attempt-sha256')
    arguments = parser.parse_args()
    action = arguments.action
    if action != 'prepare' and not re.fullmatch('[0-9a-f]{64}', arguments.receipt_sha256 or ''):
        parser.error('check/activate/rollback require --receipt-sha256')
    if action == 'rollback' and not re.fullmatch('[0-9a-f]{64}', arguments.activation_sha256 or ''):
        parser.error('rollback requires --activation-sha256 from the verified activation output')
    if action == 'recover' and not re.fullmatch('[0-9a-f]{64}', arguments.attempt_sha256 or ''):
        parser.error('recover requires --attempt-sha256 from the on-disk attempt journal')
    configure(arguments.stage, arguments.stage_sha256)
    if action == 'prepare':
        prepare()
    elif action == 'check':
        check(arguments.receipt_sha256)
    elif action == 'recover':
        recover_interrupted(receipt_sha=arguments.receipt_sha256, attempt_sha=arguments.attempt_sha256)
    else:
        switch(receipt_sha=arguments.receipt_sha256, rollback=action == 'rollback', activation_sha=arguments.activation_sha256)
