def sha(raw):
    return hashlib.sha256(raw).hexdigest()


def file_sha(path):
    return sha(Path(path).read_bytes())


def checked(path, digest):
    path = Path(path)
    if path.is_symlink() or not path.is_file() or file_sha(path) != digest:
        raise ValueError('PIN_CHANGED:' + str(path))
    return path


def ref_checked(ref):
    return checked(ref['path'], ref['sha256'])


def json_write(path, value):
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open('x', encoding='utf-8') as stream:
        json.dump(value, stream, ensure_ascii=False, sort_keys=True, indent=2)
        stream.write('\n')
        stream.flush()
        os.fsync(stream.fileno())
    sync_directory(path.parent)


def sync_directory(path):
    descriptor = os.open(path, os.O_RDONLY)
    try:
        os.fsync(descriptor)
    finally:
        os.close(descriptor)


def persist_attempt(value, expected_sha=None):
    raw = (json.dumps(value, ensure_ascii=False, sort_keys=True, indent=2) + '\n').encode()
    if expected_sha is None:
        with ATTEMPT.open('xb') as stream:
            stream.write(raw)
            stream.flush()
            os.fsync(stream.fileno())
    else:
        checked(ATTEMPT, expected_sha)
        with tempfile.NamedTemporaryFile(dir=ATTEMPT.parent, prefix='.junda-attempt-', delete=False) as stream:
            temporary = Path(stream.name)
            try:
                stream.write(raw)
                stream.flush()
                os.fsync(stream.fileno())
                checked(ATTEMPT, expected_sha)
                os.replace(temporary, ATTEMPT)
            finally:
                temporary.unlink(missing_ok=True)
    sync_directory(ATTEMPT.parent)
    return sha(raw)


