def delta_records(stage, roots, tools):
    by_kind = {'api': [], 'site': []}
    for item in stage['changes']:
        path = roots[item['kind']] / item['path']
        before = path.read_bytes() if path.exists() else None
        after = Path(item['after']['path']).read_bytes()
        proof, count = tools._diff_proof(before, after) if before is not None else (None, None)
        by_kind[item['kind']].append({'path': item['path'], 'before_sha256': item['before_sha256'],
                                      'after_sha256': sha(after), 'unified_diff_sha256': proof,
                                      'unified_diff_hunk_count': count})
    return {key: sorted(value, key=lambda item: item['path']) for key, value in by_kind.items()}


def check_allowlist(stage):
    old = json.loads(Path(stage['old_asset_manifest']['path']).read_text())
    new = json.loads(Path(stage['new_asset_manifest']['path']).read_text())
    old_map = {r['path']: r['sha256'] for r in old['files']}
    new_map = {r['path']: r['sha256'] for r in new['files']}
    expected = {item['path']: item['after']['sha256'] for item in stage['changes'] if item['kind'] == 'site'}
    if len(old_map) != len(old['files']) or len(new_map) != len(new['files']):
        raise ValueError('ASSET_MANIFEST_DUPLICATE')
    changed = {p for p, digest in expected.items() if old_map.get(p) != digest}
    if {p for p in old_map.keys() | new_map.keys() if old_map.get(p) != new_map.get(p)} != changed:
        raise ValueError('ASSET_MANIFEST_DELTA_INVALID')
    if any(new_map[path] != digest for path, digest in expected.items()):
        raise ValueError('ASSET_MANIFEST_AFTER_MISMATCH')


def replace_candidate_file(path, raw):
    mode = path.stat().st_mode & 0o777 if path.exists() else 0o644
    with tempfile.NamedTemporaryFile(dir=path.parent, prefix='.junda-overlay-', delete=False) as stream:
        temporary = Path(stream.name)
        try:
            stream.write(raw)
            stream.flush()
            os.fsync(stream.fileno())
            temporary.chmod(mode)
            os.replace(temporary, path)
        finally:
            temporary.unlink(missing_ok=True)


def clone_tree(source, target):
    # macOS cp -c uses clonefile and may fall back to a normal copy if unavailable.
    subprocess.run(['/bin/cp', '-cRp', str(source), str(target)], check=True, timeout=180)


